# ============================================================
# Задача 1.1. Анкета
# ============================================================
# Спросите у пользователя имя, возраст и город.
# Выведите строку вида: Иван, 25 лет, Москва.

def task_1_1():
    name = str(input("Введите имя: "))
    age = int(input("Введите возраст: "))
    city = str(input("Введите город: "))
    print(f"{name}, {age} лет, {city}.")

# ============================================================
# Задача 1.2. Сумма двух чисел
# ============================================================
# Запросите два целых числа и выведите их сумму,
# разность и произведение.

def task_1_2():
    first_number = int(input("Введите первое число: "))
    second_number = int(input("Введите второе число: "))
    print(f"Сумма: {first_number + second_number}")


# ============================================================
# Задача 1.3. Длина строки
# ============================================================
# Запросите строку и выведите её длину и первый символ.

def task_1_3():
    string = str(input("Введите строку: "))
    print(f"Длина строки: {len(string)}")
    print(f"Первый символ: {string[0]}")


# ============================================================
# Задача 1.4. Логический вывод
# ============================================================
# Запросите число. Выведите True, если оно положительное,
# и False в противном случае (используйте только print
# и сравнение).

def task_1_4():
    num = int(input("Введите число: "))
    print(num > 0)
    

# ============================================================
# Задача 2.1. Площадь круга
# ============================================================
# Запросите радиус (вещественное число).
# Выведите площадь круга и длину окружности с точностью
# до двух знаков.
#
# Пример:
#   In: 3.0
#   Out: S = 28.27, C = 18.85
#
# Подсказка: используйте math.pi и f-строки.

def task_2_1(radius: float) -> str:
    import math

    area = math.pi * radius**2
    circumference = 2 * math.pi * radius
    return f"S = {area:.2f}, C = {circumference:.2f}"


# ============================================================
# Задача 2.2. Обмен значений
# ============================================================
# Запросите два числа a и b. Поменяйте их значения местами
# без третьей переменной и выведите результат.
#
# Пример:
#   In: 5 10
#   Out: a = 10, b = 5

def task_2_2(a, b):

    a, b = b, a
    print(f"a = {a}, b = {b}")


# ============================================================
# Задача 2.3. Часы и минуты
# ============================================================
# Условие:
#   Запросите количество минут. Переведите его в часы и минуты.
#   Выведите результат в формате ЧЧ:ММ.
#
# Пример:
#   In: 135
#   Out: 02:15
#
# Подсказка:
#   Используйте // и %. Для ведущего нуля: f"{h:02d}:{m:02d}".

def task_2_3(minutes: int) -> str:
    hours = minutes // 60
    minutes = minutes % 60
    return f"{hours:02d}:{minutes:02d}"


# ============================================================
# Подсказки
# ============================================================
# 2.1: S = pi * r**2, C = 2 * pi * r, формат f"{S:.2f}"
# 2.3: h = minutes // 60; m = minutes % 60; f"{h:02d}:{m:02d}"

if __name__ == "__main__":
    task_1_1()
    task_1_2()
    task_1_3()
    task_1_4()
    print(task_2_1(3.0))
    task_2_2(5, 10)
    print(task_2_3(135))
