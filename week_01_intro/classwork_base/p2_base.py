#   Используйте моржовый оператор в условии while.
#
# Пример:
#   In: a
#   In: b
#   In: stop
#   Out: -> a
#        -> b
#
# Подсказка:
#   while (line := input()) != "stop":
#       print(f"-> {line}")

def task_2_5():
    print("This is task 2.5")
    while (line := input()) != "stop":
        print(f"-> {line}")


