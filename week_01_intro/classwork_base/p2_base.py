# Задача 2.4. Моржовый оператор (базово)
# ============================================================
# Условие:
#   Запросите строку. Если её длина больше 5, выведите
#   длину строки. Используйте моржовый оператор :=,
#   чтобы не вызывать len() дважды.
#
# Пример:
#   In: hello world
#   Out: 11
#
#   In: hi
#   Out: (ничего)
#
# Подсказка:
#   if (n := len(s)) > 5:
#       print(n)

def task_2_4(s: str) -> int | None:
    """Вернуть длину, если > 5, иначе None."""
    print("This is task 2.4")
    if (n := len(s)) > 5:
        print(n)
        return n
    else:
        print("Длина строки меньше или равна 5")
        return None

